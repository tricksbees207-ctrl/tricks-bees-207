-- Atomic manual start: first call seeds all current active colonies and ten checklist items.
-- Repeating the call returns the existing season without auto-enrolling later colonies.
create or replace function public.winter_start_season(p_start_year integer)
returns bigint language plpgsql security invoker set search_path=''
as $$
declare v_id bigint; v_owner uuid;
begin
  v_owner=auth.uid();
  if v_owner is null or (auth.jwt()->>'aal') <> 'aal2' then
    raise exception 'Verified sign-in required';
  end if;
  if p_start_year not between 2000 and 2200 then
    raise exception 'Invalid winter start year';
  end if;
  insert into public."Winter_Seasons"(user_id,start_year)
  values(v_owner,p_start_year)
  on conflict(user_id,start_year) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from public."Winter_Seasons"
    where user_id=v_owner and start_year=p_start_year;
    return v_id;
  end if;
  insert into public."Winter_Participation"(user_id,season_id,colony_id)
  select v_owner,v_id,id from public."Hive_Colonies"
  where user_id=v_owner and colony_status='active';
  insert into public."Winter_Checklist_Items"(user_id,participation_id,item_key,section,label)
  select v_owner,p.id,x.key,x.section,x.label
  from public."Winter_Participation" p
  cross join (values
    ('health_queen','health','Queen status reviewed'),
    ('health_strength','health','Colony strength assessed'),
    ('health_varroa','health','Varroa management reviewed'),
    ('health_treatment','health','Treatment follow-ups reviewed'),
    ('food_stores','food','Winter food stores assessed'),
    ('food_feeding','food','Fall feeding reviewed'),
    ('protection_mouse_guard','protection','Mouse guard installed or checked'),
    ('protection_moisture','protection','Moisture and ventilation setup checked'),
    ('protection_equipment','protection','Hive equipment secured'),
    ('protection_wind','protection','Wind and weather protection reviewed')
  ) as x(key,section,label)
  where p.season_id=v_id and p.user_id=v_owner;
  return v_id;
end;
$$;
revoke all on function public.winter_start_season(integer) from public, anon;
grant execute on function public.winter_start_season(integer) to authenticated;

