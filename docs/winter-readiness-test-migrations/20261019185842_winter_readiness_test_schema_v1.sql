create table if not exists public."Winter_Seasons" (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  start_year integer not null check(start_year between 2000 and 2200),
  status text not null default 'open' check(status in ('open','closed')),
  started_at timestamptz not null default now(),
  closed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(user_id,start_year),
  unique(id,user_id),
  check ((status='open' and closed_at is null) or (status='closed' and closed_at is not null))
);
create table if not exists public."Winter_Participation" (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  season_id bigint not null,
  colony_id bigint not null references public."Hive_Colonies"(id) on delete restrict,
  participation text not null default 'included' check(participation in ('included','excluded')),
  exclusion_reason text,
  prep_assessment text not null default 'unassessed' check(prep_assessment in ('unassessed','complete','concerns','incomplete')),
  prep_confirmed_at timestamptz,
  prep_notes text,
  added_at timestamptz not null default now(),
  unique(season_id,colony_id),
  unique(id,user_id),
  foreign key(season_id,user_id) references public."Winter_Seasons"(id,user_id) on delete restrict
);
create table if not exists public."Winter_Checklist_Items" (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  participation_id bigint not null,
  item_key text not null,
  section text not null check(section in ('health','food','protection','custom')),
  label text not null check(length(trim(label))>0),
  is_custom boolean not null default false,
  status text not null default 'not_checked' check(status in ('not_checked','complete','needs_attention','not_applicable')),
  status_changed_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  unique(participation_id,item_key),
  foreign key(participation_id,user_id) references public."Winter_Participation"(id,user_id) on delete restrict
);
create table if not exists public."Winter_Observations" (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  participation_id bigint not null,
  observed_on date not null,
  activity text not null default 'not_checked' check(activity in ('not_checked','bees_seen','none_seen','heard','concern')),
  heft text not null default 'not_checked' check(heft in ('not_checked','heavy','moderate','light','measured')),
  measured_weight numeric(9,2) check(measured_weight>0),
  weight_unit text check(weight_unit in ('lb','kg')),
  entrance text not null default 'not_checked' check(entrance in ('not_checked','clear','snow_ice','dead_bees','concern')),
  moisture text not null default 'not_checked' check(moisture in ('not_checked','no_visible_concern','condensation','damp')),
  supplemental_food text not null default 'not_checked' check(supplemental_food in ('not_checked','none_added','added_in_feeding_log','concern')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key(participation_id,user_id) references public."Winter_Participation"(id,user_id) on delete restrict,
  check ((heft='measured' and measured_weight is not null and weight_unit is not null) or
         (heft<>'measured' and measured_weight is null and weight_unit is null))
);
create table if not exists public."Winter_Outcomes" (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  participation_id bigint not null,
