-- Validate that participating colony belongs to signed-in owner. Uses existing colony table read-only.
create or replace function public.winter_validate_participant_owner()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if not exists(select 1 from public."Hive_Colonies" c where c.id=new.colony_id and c.user_id=new.user_id)
  then raise exception 'Colony does not belong to the season owner'; end if;
  return new;
end;
$$;
create trigger winter_check_colony_owner
before insert or update on public."Winter_Participation"
for each row execute function public.winter_validate_participant_owner();

-- Append-only history, generated in database for all changes (including corrections).
create or replace function public.winter_audit_changes()
returns trigger language plpgsql security definer set search_path=''
as $$
declare v_user uuid; v_id bigint;
begin
  if TG_OP='DELETE' then
    v_user=old.user_id; v_id=old.id;
  else
    v_user=new.user_id; v_id=new.id;
  end if;
  insert into public."Winter_Audit_History"
    (user_id,entity_type,entity_id,event_type,before_record,after_record)
  values
    (v_user,TG_TABLE_NAME,v_id,TG_OP,
      case when TG_OP in ('UPDATE','DELETE') then to_jsonb(old) else null end,
      case when TG_OP in ('UPDATE','INSERT') then to_jsonb(new) else null end);
  return coalesce(new,old);
end;
$$;
create trigger winter_audit_seasons after insert or update or delete on public."Winter_Seasons"
for each row execute function public.winter_audit_changes();
create trigger winter_audit_participation after insert or update or delete on public."Winter_Participation"
for each row execute function public.winter_audit_changes();
create trigger winter_audit_checklist after insert or update or delete on public."Winter_Checklist_Items"
