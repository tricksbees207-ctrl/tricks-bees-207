CREATE OR REPLACE FUNCTION public.winter_add_colony(p_season_id bigint, p_colony_id bigint, p_include boolean, p_reason text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare v_owner uuid; v_id bigint;
begin
 v_owner=auth.uid();
 if v_owner is null or (auth.jwt()->>'aal') <> 'aal2' then
   raise exception 'Verified sign-in required';
 end if;
 if not exists(select 1 from public."Winter_Seasons"
               where id=p_season_id and user_id=v_owner and status='open') then
   raise exception 'No open season belongs to this account';
 end if;
 if not exists(select 1 from public."Hive_Colonies"
               where id=p_colony_id and user_id=v_owner and colony_status='active') then
   raise exception 'Only your active colonies can be added';
 end if;
 if not p_include and nullif(trim(coalesce(p_reason,'')),'') is null then
   raise exception 'Please record a reason for excluding this colony';
 end if;
 insert into public."Winter_Participation"(user_id,season_id,colony_id,participation,exclusion_reason)
 values(v_owner,p_season_id,p_colony_id,case when p_include then 'included' else 'excluded' end,
        case when p_include then null else trim(p_reason) end)
 on conflict(season_id,colony_id) do nothing
 returning id into v_id;
 if v_id is null then
   raise exception 'This colony already belongs to the season';
 end if;
 if p_include then
   insert into public."Winter_Checklist_Items"(user_id,participation_id,item_key,section,label)
   select v_owner,v_id,x.key,x.section,x.label from (values
     ('health_queen','health','Queen status reviewed'),
     ('health_strength','health','Colony strength assessed'),
     ('health_varroa','health','Varroa management reviewed'),
     ('health_treatment','health','Treatment follow-ups reviewed'),
     ('food_stores','food','Winter food stores assessed'),
     ('food_feeding','food','Fall feeding reviewed'),
     ('protection_mouse_guard','protection','Mouse guard installed or checked'),
     ('protection_moisture','protection','Moisture and ventilation setup checked'),
     ('protection_equipment','protection','Hive equipment secured'),
     ('protection_wind','protection','Wind and weather protection reviewed')
   ) as x(key,section,label);
 end if;
 return v_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.winter_audit_changes()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_user uuid; v_id bigint;
begin
  if TG_OP='DELETE' then
    v_user=old.user_id; v_id=old.id;
  else
    v_user=new.user_id; v_id=new.id;
  end if;
  insert into public."Winter_Audit_History"
    (user_id,entity_type,entity_id,event_type,before_record,after_record)
  values
    (v_user,TG_TABLE_NAME,v_id,TG_OP,
      case when TG_OP in ('UPDATE','DELETE') then to_jsonb(old) else null end,
      case when TG_OP in ('UPDATE','INSERT') then to_jsonb(new) else null end);
  return coalesce(new,old);
end;
$function$;

CREATE OR REPLACE FUNCTION public.winter_close_season(p_season_id bigint, p_unresolved jsonb DEFAULT '{}'::jsonb, p_closure_notes text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
 v_owner uuid;
 v_start_year integer;
 v_state text;
 v_closed timestamptz;
 v_version integer;
 v_people jsonb;
 v_missing integer;
begin
 v_owner=auth.uid();
 if v_owner is null or (auth.jwt()->>'aal') <> 'aal2' then
   raise exception 'Verified MFA sign-in required';
 end if;
 if p_unresolved is null or jsonb_typeof(p_unresolved)<>'object' then
   raise exception 'Unresolved outcome explanations must be a JSON object';
 end if;
 select s.start_year,s.status into v_start_year,v_state
 from public."Winter_Seasons" s
 where s.id=p_season_id and s.user_id=v_owner for update;
 if v_state is distinct from 'open' then
   raise exception 'No open season found for this account';
 end if;

 select count(*) into v_missing
 from public."Winter_Participation" p
 left join public."Winter_Outcomes" o on o.participation_id=p.id and o.user_id=v_owner
 where p.season_id=p_season_id and p.user_id=v_owner and p.participation='included'
   and (o.id is null or o.outcome='not_assessed')
   and nullif(trim(coalesce(p_unresolved->>(p.id::text),'')),'') is null;
 if v_missing>0 then
   raise exception 'Closure requires an explanation for each of % unresolved colonies',v_missing;
 end if;
 v_closed=clock_timestamp();
 select coalesce(jsonb_agg(
   jsonb_build_object(
     'participation',to_jsonb(p),
     'colony',to_jsonb(c),
     'unresolved_reason',nullif(trim(coalesce(p_unresolved->>(p.id::text),'')),''),
     'checklist',(select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]'::jsonb)
                  from public."Winter_Checklist_Items" i where i.participation_id=p.id and i.user_id=v_owner),
     'observations',(select coalesce(jsonb_agg(to_jsonb(o) order by o.observed_on,o.id),'[]'::jsonb)
                     from public."Winter_Observations" o where o.participation_id=p.id and o.user_id=v_owner and o.deleted_at is null),
     'outcome',(select to_jsonb(o) from public."Winter_Outcomes" o
                where o.participation_id=p.id and o.user_id=v_owner),
     'linked_loss',(select to_jsonb(l) from public."Winter_Outcomes" o
                    join public."Hive_Losses" l on l.id=o.loss_record_id and l.user_id=v_owner and l.hive_id=c.hive_id
                    where o.participation_id=p.id and o.user_id=v_owner),
     'spring_inspections',(select coalesce(jsonb_agg(to_jsonb(i) order by i.inspection_date,i.id),'[]'::jsonb)
                           from public."Hive_Inspections" i
                           where i.colony_id=p.colony_id and i.hive_id=c.hive_id
                             and i.inspection_date between make_date(v_start_year+1,1,1) and v_closed::date),
     'last_inspection',(select to_jsonb(i) from public."Hive_Inspections" i
                        where i.colony_id=p.colony_id and i.hive_id=c.hive_id and i.inspection_date<=v_closed::date
                        order by i.inspection_date desc,i.id desc limit 1),
     'last_feeding',(select to_jsonb(f) from public."Hive_Feedings" f
                     where f.colony_id=p.colony_id and f.hive_id=c.hive_id and f.user_id=v_owner and f.feed_date<=v_closed::date
                     order by f.feed_date desc,f.id desc limit 1),
     'last_treatment',(select to_jsonb(t) from public."Hive_Treatments" t
                       where t.colony_id=p.colony_id and t.hive_id=c.hive_id and t.user_id=v_owner and t.treatment_date<=v_closed::date
                       order by t.treatment_date desc,t.id desc limit 1)
   ) order by p.id),'[]'::jsonb)
 into v_people
 from public."Winter_Participation" p
 join public."Hive_Colonies" c on c.id=p.colony_id and c.user_id=v_owner
 where p.season_id=p_season_id and p.user_id=v_owner;

 update public."Winter_Seasons" set status='closed',closed_at=v_closed,updated_at=v_closed
 where id=p_season_id and user_id=v_owner;
 select coalesce(max(version),0)+1 into v_version
 from public."Winter_Snapshots" where season_id=p_season_id and user_id=v_owner;
 insert into public."Winter_Snapshots"
   (user_id,season_id,version,snapshot,closure_reason,created_at)
 values
   (v_owner,p_season_id,v_version,
    jsonb_build_object('schema_version',1,'season_year',v_start_year,'season_id',p_season_id,
                       'closed_at',v_closed,'participants',v_people,'closure_notes',p_closure_notes),
    p_closure_notes,v_closed);
 return v_version;
end;
$function$;

