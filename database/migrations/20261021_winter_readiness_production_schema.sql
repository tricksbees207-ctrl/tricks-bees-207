CREATE OR REPLACE FUNCTION public.winter_guard_child_mutation()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_owner uuid; v_season bigint; v_state text;
begin
 if TG_OP='DELETE' then
   raise exception 'Winter history is retained; deletion is not allowed';
 end if;
 if TG_OP='UPDATE' then
   if TG_TABLE_NAME='Winter_Observations' then
     if old.deleted_at is not null then
       raise exception 'Deleted winter observations cannot be edited';
     end if;
   end if;
   if new.id<>old.id or new.user_id<>old.user_id then
     raise exception 'Cannot reassign winter record identity';
   end if;
   if TG_TABLE_NAME='Winter_Participation' then
     if new.season_id<>old.season_id or new.colony_id<>old.colony_id then
       raise exception 'Cannot reassign a winter participant';
     end if;
   else
     if new.participation_id<>old.participation_id then
       raise exception 'Cannot reassign a winter record';
     end if;
   end if;
 end if;
 if TG_TABLE_NAME='Winter_Participation' then
   v_season=new.season_id;
 else
   select p.season_id into v_season from public."Winter_Participation" p
   where p.id=new.participation_id and p.user_id=new.user_id;
 end if;
 select s.status,s.user_id into v_state,v_owner
 from public."Winter_Seasons" s where s.id=v_season for share;
 if v_state is distinct from 'open' or v_owner is distinct from new.user_id then
   raise exception 'Winter season closed or participant ownership invalid';
 end if;
 return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.winter_reopen_season(p_season_id bigint, p_reason text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_owner uuid; v_state text;
begin
 v_owner=auth.uid();
 if v_owner is null or (auth.jwt()->>'aal') <> 'aal2' then
   raise exception 'Verified MFA sign-in required';
 end if;
 if nullif(trim(coalesce(p_reason,'')),'') is null then
   raise exception 'Reason for reopening is required';
 end if;
 select s.status into v_state from public."Winter_Seasons" s
 where s.id=p_season_id and s.user_id=v_owner for update;
 if v_state is distinct from 'closed' then
   raise exception 'Only a closed season may be reopened';
 end if;
 update public."Winter_Seasons"
 set status='open',closed_at=null,updated_at=clock_timestamp(),
     last_reopen_reason=trim(p_reason)
 where id=p_season_id and user_id=v_owner;
 return true;
end;
$function$;

CREATE OR REPLACE FUNCTION public.winter_start_season(p_start_year integer)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare v_id bigint; v_owner uuid;
begin
  v_owner=auth.uid();
  if v_owner is null or (auth.jwt()->>'aal') <> 'aal2' then
    raise exception 'Verified sign-in required';
  end if;
  if p_start_year not between 2000 and 2200 then
    raise exception 'Invalid winter start year';
  end if;
  insert into public."Winter_Seasons"(user_id,start_year)
  values(v_owner,p_start_year)
  on conflict(user_id,start_year) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from public."Winter_Seasons"
    where user_id=v_owner and start_year=p_start_year;
    return v_id;
  end if;
  insert into public."Winter_Participation"(user_id,season_id,colony_id)
  select v_owner,v_id,id from public."Hive_Colonies"
  where user_id=v_owner and colony_status='active';
  insert into public."Winter_Checklist_Items"(user_id,participation_id,item_key,section,label)
  select v_owner,p.id,x.key,x.section,x.label
  from public."Winter_Participation" p
  cross join (values
    ('health_queen','health','Queen status reviewed'),
    ('health_strength','health','Colony strength assessed'),
    ('health_varroa','health','Varroa management reviewed'),
    ('health_treatment','health','Treatment follow-ups reviewed'),
    ('food_stores','food','Winter food stores assessed'),
    ('food_feeding','food','Fall feeding reviewed'),
    ('protection_mouse_guard','protection','Mouse guard installed or checked'),
    ('protection_moisture','protection','Moisture and ventilation setup checked'),
    ('protection_equipment','protection','Hive equipment secured'),
    ('protection_wind','protection','Wind and weather protection reviewed')
  ) as x(key,section,label)
