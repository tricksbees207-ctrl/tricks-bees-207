  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id),
  description text NOT NULL CHECK (length(btrim(description)) BETWEEN 1 AND 240),
