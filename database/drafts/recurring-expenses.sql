-- One atomic database transaction to record a payment and move its due date.
-- SECURITY INVOKER means the expense-table and schedule-table RLS policies still apply.
CREATE FUNCTION public.record_recurring_expense(
  p_template_id bigint, p_expected_due_date date, p_paid_date date, p_actual_amount numeric DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp
AS $$
DECLARE
  schedule_row public."Apiary_Recurring_Expenses"%ROWTYPE;
  months_forward integer;
  target_month_first date;
  target_month_last date;
  next_date date;
  new_expense_id bigint;
BEGIN
  IF auth.uid() IS NULL OR p_paid_date IS NULL OR p_expected_due_date IS NULL THEN
    RAISE EXCEPTION 'Valid sign-in and dates are required';
  END IF;
  IF p_actual_amount IS NOT NULL AND (p_actual_amount < 0 OR p_actual_amount > 9999999999.99) THEN
    RAISE EXCEPTION 'Actual payment amount is invalid';
  END IF;
  SELECT * INTO schedule_row
    FROM public."Apiary_Recurring_Expenses"
    WHERE id = p_template_id AND user_id = auth.uid()
    FOR UPDATE;
  IF NOT FOUND OR NOT schedule_row.active THEN
    RAISE EXCEPTION 'Recurring payment is not available or is paused';
  END IF;
  IF schedule_row.next_due_date <> p_expected_due_date THEN
    RAISE EXCEPTION 'Due date has changed; refresh before recording';
  END IF;
  INSERT INTO public."Apiary_Expenses" (
    user_id, hive_id, expense_date, category, description, vendor,
    amount, payment_method, notes, recurring_template_id, recurring_due_date
  ) VALUES (
    schedule_row.user_id, schedule_row.hive_id, p_paid_date, schedule_row.category,
    schedule_row.description, schedule_row.vendor, coalesce(p_actual_amount,schedule_row.amount),
    schedule_row.payment_method, schedule_row.notes, schedule_row.id, p_expected_due_date
  ) RETURNING id INTO new_expense_id;

  months_forward := CASE schedule_row.frequency
    WHEN 'monthly' THEN 1 WHEN 'quarterly' THEN 3 ELSE 12 END;
  target_month_first := (date_trunc('month',schedule_row.next_due_date::timestamp)
    + make_interval(months => months_forward))::date;
  target_month_last := (target_month_first + interval '1 month - 1 day')::date;
  -- Anchor from the original billing day, including 29th/30th/31st of month.
  next_date := target_month_first + (LEAST(
    EXTRACT(day FROM schedule_row.anchor_date)::integer,
    EXTRACT(day FROM target_month_last)::integer
  ) - 1);
  UPDATE public."Apiary_Recurring_Expenses"
    SET next_due_date = next_date, updated_at = now()
    WHERE id = schedule_row.id AND user_id = auth.uid();
  RETURN new_expense_id;
END
$$;
REVOKE ALL ON FUNCTION public.record_recurring_expense(bigint,date,date,numeric) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.record_recurring_expense(bigint,date,date,numeric) TO authenticated;

COMMIT;
