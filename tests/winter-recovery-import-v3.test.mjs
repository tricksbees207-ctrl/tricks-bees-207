import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const page=readFileSync('recovery-test.html','utf8');
const sql=readFileSync('database/migrations/20261021_winter_v3_recovery_test_import.sql','utf8');
const verifier=readFileSync('js/apiary-backup-verifier-v3-test.js','utf8');
assert(page.includes("from './js/apiary-backup-verifier-v3-test.js'"),'Test Lab reads v3 backup ZIP');
assert(page.includes("archive?.manifest?.version===3"),'v3 25-table selector');
assert(page.includes("recovery_test_import_v3"),'v3 importer RPC');
assert(page.includes("canonical(got)===canonical(wanted)"),'compare nested historical JSON');
assert(page.includes("$('clearTestStorage').disabled=true"),'legacy cleanup must be disabled');
assert(verifier.includes("manifest.version===3"),'v3 parser supported');
assert(verifier.includes("'Winter_Audit_History'"),'audit archive supported');
assert(verifier.includes("'Winter_Snapshots'"),'snapshot archive supported');
assert(sql.includes("count(*) FROM jsonb_object_keys(p_tables)) <> 25"),'require exactly 25 tables');
assert(sql.includes("IF v_before<>0"),'nonempty destination guard present');
assert(sql.indexOf('IF v_before<>0') < sql.indexOf('IF NOT p_apply'),'nonempty guard BEFORE preview');
assert(sql.indexOf('IF NOT p_apply') < sql.indexOf("IF v_table='Winter_Audit_History'"),'preview BEFORE inserts');
assert(sql.includes("'aal2'"),'MFA required');
assert(sql.includes("NOT recovery_test_private.is_owner()"),'owner required');
assert(sql.includes("'Winter_Snapshots'"),'snapshot restoration');
assert(sql.includes("'Winter_Audit_History'"),'audit restoration');
assert(!sql.includes('TRUNCATE TABLE'),'no truncation');
assert(!sql.includes('DROP TABLE'),'no drop');
assert(!page.includes("client.rpc('recovery_test_import',{p_tables:archive.data.tables"),'RPC routed by archive');
const scripts=[...page.matchAll(/<script\s+type="module"[^>]*>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length,1,'Test Lab has exactly one module script');
const temp=join(mkdtempSync(join(tmpdir(),'winter-test-page-')),'page.mjs');
writeFileSync(temp,scripts[0][1]);
const result=spawnSync(process.execPath,['--check',temp],{encoding:'utf8'});
assert.equal(result.status,0,'Test page script must parse: '+result.stderr);
console.log('PASS: v3 ZIP routing, 25-table SQL and safety invariants, readback, cleanup disabled, JS syntax.');
